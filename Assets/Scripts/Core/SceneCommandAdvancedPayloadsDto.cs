using System;

namespace ShotField.Core
{
    /// <summary>
    /// Payload parameters for establishing spatial or directorial constraints.
    /// Supports Axis, Framing, and Visibility constraints.
    /// </summary>
    [Serializable]
    public class SetConstraintPayload
    {
        public string constraintId;
        public string ruleType;
        public string sourceActorId;
        public string targetActorId;
        public string subjectPropId;
        public bool isBlocking;
        public bool isWaivable;
        public float toleranceDistance;

        public SetConstraintPayload()
        {
            isBlocking = true;
            isWaivable = false;
            toleranceDistance = 0.1f;
        }
    }

    /// <summary>
    /// Payload parameters for proposing a camera shot composition.
    /// </summary>
    [Serializable]
    public class ProposeShotPayload
    {
        public string shotId;
        public Vector3Dto cameraPosition;
        public QuaternionDto cameraRotation;
        public float focalLength;
        public float fieldOfView;
        public string shotSize;
        public string intentDescription;

        public ProposeShotPayload()
        {
            focalLength = 35.0f;
            fieldOfView = 60.0f;
            shotSize = "Medium";
        }
    }

    /// <summary>
    /// Audit result generated by the 4-gate command validation pipeline.
    /// Records which gate rejected a command and why.
    /// </summary>
    [Serializable]
    public class CommandValidationResultDto
    {
        public bool isValid;
        public int failedGateStep;
        public string errorCode;
        public string rejectionReason;
        public string validatedCommandId;

        public CommandValidationResultDto()
        {
        }

        public static CommandValidationResultDto CreateValid(string commandId)
        {
            return new CommandValidationResultDto
            {
                isValid = true,
                failedGateStep = 0,
                errorCode = string.Empty,
                rejectionReason = string.Empty,
                validatedCommandId = commandId
            };
        }

        public static CommandValidationResultDto CreateInvalid(string commandId, int gateStep, string errCode, string reason)
        {
            return new CommandValidationResultDto
            {
                isValid = false,
                failedGateStep = gateStep,
                errorCode = errCode,
                rejectionReason = reason,
                validatedCommandId = commandId
            };
        }
    }

    /// <summary>
    /// Execution status and post-mutation audit information for a scene command.
    /// </summary>
    [Serializable]
    public class CommandExecutionResultDto
    {
        public bool isSuccess;
        public string commandId;
        public string executionLog;
        public long executedTimestampUtc;
        public PassportSummaryDto updatedPassport;

        public CommandExecutionResultDto()
        {
            executedTimestampUtc = DateTimeOffset.UtcNow.ToUnixTimeMilliseconds();
        }

        public CommandExecutionResultDto(string id, bool success, string log, PassportSummaryDto passport = null)
        {
            commandId = id;
            isSuccess = success;
            executionLog = log;
            executedTimestampUtc = DateTimeOffset.UtcNow.ToUnixTimeMilliseconds();
            updatedPassport = passport;
        }
    }
}
